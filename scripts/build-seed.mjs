// Builds supabase/seed.sql from supabase/seed/listings.mjs and the HTE list CSV.
// Run: node scripts/build-seed.mjs   (validates enums and references, fails loudly)
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import * as data from "../supabase/seed/listings.mjs";

const ENUMS = {
  apply_route: ["direct_hr_email", "portal_only", "form", "referral", "unknown"],
  contact_purpose: ["resume_intake", "questions_only", "help_desk", "unknown"],
  contact_status: ["reply_received", "published_untested", "bounced", "wrong_purpose"],
  role_category: ["dev", "qa", "it_support", "network", "data", "cyber", "automation", "ui_ux", "business_analyst", "other"],
  dev_exposure: ["high", "some", "low", "low_repetitive", "unknown"],
  setup: ["onsite", "hybrid", "remote", "unknown"],
  employment_type: ["full_time", "part_time", "unknown"],
  moa_requirement: ["existing_campus_moa_required", "new_partner_ok", "own_company_moa", "unknown"],
  allowance_basis: ["per_day", "per_month", "per_hour", "unknown"],
  allowance_status: ["disclosed", "not_disclosed", "unpaid", "benefits_only"],
  accepts_nov_start: ["yes", "no", "ask"],
  apply_channel: ["jobstreet", "linkedin", "indeed", "prosple", "kalibrr", "bossjob", "company_portal", "email", "forms", "facebook", "other"],
  post_status: ["open", "closed", "unconfirmed", "recurring_program", "no_post_cold_email"],
  fact_source_type: ["official_post", "company_site", "hr_reply", "employee_review", "employer_marketing", "classmate_report", "school_document"],
  fact_state: ["confirmed", "reported", "historical", "unknown"],
};
const HTE_SOURCE = "NU Laguna AILPO: FINAL LIST OF HTEs FOR 26-27.pdf";

const errors = [];
const check = (ok, msg) => { if (!ok) errors.push(msg); };
const checkEnum = (kind, value, where) => {
  if (value !== undefined) check(ENUMS[kind].includes(value), `${where}: bad ${kind} "${value}"`);
};

// stable ids so re-generating the file gives the same rows
const uuid = (key) => {
  const h = createHash("sha1").update(`ojt-hunter:${key}`).digest("hex");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-5${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
};
const q = (v) => {
  if (v === undefined || v === null) return "null";
  if (typeof v === "number" || typeof v === "boolean") return String(v);
  if (Array.isArray(v)) return v.length ? `array[${v.map(q).join(", ")}]::text[]` : "'{}'::text[]";
  return `'${String(v).replace(/'/g, "''")}'`;
};
const checkedAt = (d) => (d ? `'${d}T12:00:00+08:00'` : "null");

// minimal CSV parser (quoted fields, doubled quotes)
function parseCsv(text) {
  const rows = [];
  let row = [], field = "", quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ",") { row.push(field); field = ""; }
    else if (c === "\n" || c === "\r") {
      if (c === "\r" && text[i + 1] === "\n") i++;
      row.push(field); field = "";
      if (row.some((x) => x !== "")) rows.push(row);
      row = [];
    } else field += c;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  return rows;
}

const hteRows = parseCsv(readFileSync(new URL("../supabase/seed/hte_list_2026-27.csv", import.meta.url), "utf8")).slice(1);
const hteByNo = new Map(hteRows.map(([no, name]) => [Number(no), name]));
check(hteRows.length === 530, `expected 530 HTE rows, got ${hteRows.length}`);

const companyIds = new Map(data.companies.map((c) => [c.slug, uuid(`company:${c.slug}`)]));
check(companyIds.size === data.companies.length, "duplicate company slug");

const out = [];
out.push("-- GENERATED by scripts/build-seed.mjs from supabase/seed/listings.mjs. Do not edit by hand.");
out.push("-- Applies once to an empty database. Everything lands unpublished for review.");
out.push("begin;");
out.push("do $$ begin if exists (select 1 from public.companies) then raise exception 'seed already applied'; end if; end $$;");
out.push("");
out.push(`insert into public.app_config (campus, hte_list_version, hte_list_public) values (${q(data.CAMPUS)}, ${q(data.HTE_VERSION)}, true)`);
out.push("  on conflict (id) do update set campus = excluded.campus, hte_list_version = excluded.hte_list_version, hte_list_public = excluded.hte_list_public;");
out.push("");

out.push("insert into public.hte_list_entries (list_version, entry_no, name_as_listed, normalized_name) values");
out.push(hteRows.map(([no, name]) => `  (${q(data.HTE_VERSION)}, ${Number(no)}, ${q(name)}, public.normalize_company_name(${q(name)}))`).join(",\n") + ";");
out.push("");

out.push("insert into public.checklist_templates (item_key, label, can_do_without_company, sort_order) values");
out.push(data.checklist.map(([key, label, now], i) => `  (${q(key)}, ${q(label)}, ${now}, ${(i + 1) * 10})`).join(",\n") + ";");
out.push("");

const facts = [];
for (const c of data.companies) {
  checkEnum("apply_route", c.apply_route, c.slug);
  const id = companyIds.get(c.slug);
  out.push(`insert into public.companies (id, slug, name, legal_name, aliases, website, careers_url, industry, hq_location, description, founded_year, size_text, background_source, background_checked_on, apply_route) values (${[
    q(id), q(c.slug), q(c.name), q(c.legal_name), q(c.aliases ?? []), q(c.website), q(c.careers_url), q(c.industry), q(c.hq_location),
    q(c.description), q(c.founded_year), q(c.size_text), q(c.background_source), c.background_checked_on ? `${q(c.background_checked_on)}::date` : "null",
    `${q(c.apply_route ?? "unknown")}::public.apply_route`,
  ].join(", ")});`);

  const extra = data.partnershipNotes[c.slug] ?? {};
  const pid = uuid(`partnership:${c.slug}`);
  if (c.hte?.length) {
    for (const no of c.hte) check(hteByNo.has(no), `${c.slug}: HTE entry #${no} not in list`);
    const matched = hteByNo.get(c.hte[0]);
    out.push(`insert into public.partnerships (id, company_id, campus, status, hte_entry_id, matched_name_as_listed, source, notes) values (${q(pid)}, ${q(id)}, ${q(data.CAMPUS)}, ${q(extra.status ?? "listed_in_hte")}, (select id from public.hte_list_entries where list_version = ${q(data.HTE_VERSION)} and entry_no = ${c.hte[0]}), ${q(matched)}, ${q(HTE_SOURCE)}, ${q(extra.notes)});`);
    facts.push({ entity: "partnership", id: pid, field: "status", value: `Listed as ${matched} (#${c.hte[0]})`, type: "school_document", state: "confirmed", date: data.D22 });
  } else {
    const notes = extra.notes ?? `Not found in the ${data.HTE_VERSION} list. That does not mean there is no MOA. Ask your FIC.`;
    out.push(`insert into public.partnerships (id, company_id, campus, status, source, notes) values (${q(pid)}, ${q(id)}, ${q(data.CAMPUS)}, ${q(extra.status ?? "not_listed")}, ${q(HTE_SOURCE)}, ${q(notes)});`);
    facts.push({ entity: "partnership", id: pid, field: "status", value: `Not found in the ${data.HTE_VERSION} list`, type: "school_document", state: "confirmed", date: data.D22 });
  }
}
out.push("");

for (const m of data.moaRequests) {
  check(companyIds.has(m.company), `moa request: unknown company ${m.company}`);
  out.push(`insert into public.moa_requests (company_id, campus, status, requested_on, requested_via, last_update, notes) values (${q(companyIds.get(m.company))}, ${q(data.CAMPUS)}, ${q(m.status)}, ${q(m.requested_on)}::date, ${q(m.requested_via)}, ${q(m.requested_on)}::date, ${q(m.notes)});`);
}
out.push("");

for (const ct of data.contacts) {
  check(companyIds.has(ct.company), `contact: unknown company ${ct.company}`);
  checkEnum("contact_purpose", ct.purpose, ct.email);
  checkEnum("contact_status", ct.status, ct.email);
  out.push(`insert into public.company_contacts (company_id, email, purpose, status, bounce_code, source, observed_on, notes) values (${q(companyIds.get(ct.company))}, ${q(ct.email)}, ${q(ct.purpose)}, ${q(ct.status)}, ${q(ct.bounce_code)}, ${q(ct.source)}, ${q(ct.observed_on)}::date, ${q(ct.notes)});`);
}
out.push("");

const slugs = new Set();
for (const o of data.opportunities) {
  const where = o.slug;
  check(!slugs.has(o.slug), `duplicate opportunity slug ${o.slug}`);
  slugs.add(o.slug);
  check(companyIds.has(o.company), `${where}: unknown company ${o.company}`);
  for (const k of ["role_category", "dev_exposure", "setup", "employment_type", "moa_requirement", "allowance_basis", "allowance_status", "accepts_nov_start", "apply_channel", "post_status"]) checkEnum(k, o[k], where);
  const status = o.allowance_status ?? "not_disclosed";
  const hasAmount = [o.allowance_amount, o.allowance_min, o.allowance_max].some((v) => v != null);
  check(status === "disclosed" || !hasAmount, `${where}: amount set but allowance not disclosed`);
  check(status !== "disclosed" || hasAmount, `${where}: disclosed allowance without an amount`);
  check(o.checked, `${where}: missing checked date`);

  const id = uuid(`opportunity:${o.slug}`);
  const cols = {
    id: q(id), slug: q(o.slug), company_id: q(companyIds.get(o.company)), title: q(o.title),
    role_category: q(o.role_category ?? "other"), duties: q(o.duties), tech_stack: q(o.tech_stack ?? []),
    dev_exposure: q(o.dev_exposure ?? "unknown"), city: q(o.city), office_address: q(o.office_address),
    setup: q(o.setup ?? "unknown"), onsite_days_per_week: q(o.onsite_days_per_week), employment_type: q(o.employment_type ?? "unknown"),
    moa_requirement: q(o.moa_requirement ?? "unknown"), schedule_text: q(o.schedule_text),
    allowance_amount: q(o.allowance_amount), allowance_min: q(o.allowance_min), allowance_max: q(o.allowance_max),
    allowance_basis: q(o.allowance_basis ?? "unknown"), allowance_status: q(status), allowance_source: q(o.allowance_source),
    allowance_verified: q(o.allowance_verified ?? false), required_hours_min: q(o.required_hours_min), required_hours_max: q(o.required_hours_max),
    duration_text: q(o.duration_text), intake_text: q(o.intake_text), accepts_nov_start: q(o.accepts_nov_start ?? "ask"),
    school_requirements: q(o.school_requirements), apply_url: q(o.apply_url), apply_channel: q(o.apply_channel ?? "other"),
    apply_instructions: q(o.apply_instructions), post_status: q(o.post_status ?? "unconfirmed"), last_checked_at: checkedAt(o.checked),
    source_url: q(o.source_url ?? o.apply_url), notes: q(o.notes),
  };
  out.push(`insert into public.opportunities (${Object.keys(cols).join(", ")}) values (${Object.values(cols).join(", ")});`);

  const obs = o.obs ?? [];
  if (o.allowance_source && !obs.some((x) => x.field === "allowance")) {
    const state = status === "unpaid" && o.allowance_verified ? "confirmed" : o.allowance_verified ? "confirmed" : "reported";
    facts.push({ entity: "opportunity", id, field: "allowance", value: o.allowance_source, type: "official_post", state, date: o.checked, url: o.source_url ?? o.apply_url });
  }
  if (o.dev_exposure && o.checked === data.D23) {
    facts.push({ entity: "opportunity", id, field: "dev_exposure", value: o.dev_exposure, type: "classmate_report", state: "reported", date: o.checked });
  }
  for (const x of obs) facts.push({ entity: "opportunity", id, field: x.field, value: x.value, type: x.type, state: x.state, date: x.date, url: o.source_url ?? o.apply_url });
}
out.push("");

for (const f of facts) {
  checkEnum("fact_source_type", f.type, `fact ${f.field}`);
  checkEnum("fact_state", f.state, `fact ${f.field}`);
}
out.push("insert into public.fact_sources (entity, entity_id, field, value, source_url, source_type, state, observed_on) values");
out.push(facts.map((f) => `  (${q(f.entity)}, ${q(f.id)}, ${q(f.field)}, ${q(f.value)}, ${q(f.url)}, ${q(f.type)}, ${q(f.state)}, ${q(f.date)}::date)`).join(",\n") + ";");
out.push("");

out.push("-- users who signed up before the trigger existed get a profile and checklist too");
out.push("insert into public.profiles (user_id, display_name, email) select u.id, u.raw_user_meta_data ->> 'name', u.email from auth.users u on conflict (user_id) do nothing;");
out.push("insert into public.deployment_checklist (user_id, item_key) select u.id, t.item_key from auth.users u cross join public.checklist_templates t on conflict (user_id, item_key) do nothing;");
out.push("commit;");

const sql = out.join("\n") + "\n";
check(!sql.includes("—"), "em dash found in seed text");
if (errors.length) {
  console.error(`Seed has ${errors.length} problem(s):\n- ${errors.join("\n- ")}`);
  process.exit(1);
}
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log(`seed.sql: ${data.companies.length} companies, ${data.opportunities.length} opportunities, ${data.contacts.length} contacts, ${facts.length} facts, ${hteRows.length} HTE entries, ${data.checklist.length} checklist items`);
